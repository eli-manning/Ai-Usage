/* Draws each provider's mini (pet.js, looks.js) on a fake canvas and prints the pixels as Swift for the menu bar
   icon, so the icon is always the same critter as the mini. Run from mac-native: node scripts/tray-sprites.js */
const fs = require('fs');
const W = require('path').join(__dirname, '../Sources/AiUsage/Resources/web');
const mkCanvas = () => {
  const c = { width: 0, height: 0, style: {}, px: {}, setAttribute() {}, getBoundingClientRect: () => ({ left: 0, top: 0, width: 46, height: 34 }) };
  const ctx = { fillStyle: '', imageSmoothingEnabled: false,
    fillRect(x, y) { c.px[x + ',' + y] = ctx.fillStyle; }, clearRect() { c.px = {}; }, drawImage() {} };
  c.getContext = () => ctx;
  return c;
};
global.document = { hidden: false, createElement: () => mkCanvas() };
global.window = global;
eval(fs.readFileSync(W + '/pet.js', 'utf8'));
eval(fs.readFileSync(W + '/looks.js', 'utf8'));
const el = { classList: { add() {} }, innerHTML: '', dataset: {}, appendChild() {} };
const out = {};
Critter.addPose('iconFine', { anim: 'none' });
Critter.addPose('iconBusy', { eyes: 'dash', anim: 'none' });
Critter.addPose('iconError', { eyes: 'x', anim: 'none' });
for (const [id, L] of Object.entries(MINI_LOOKS)) {
  out[id] = {};
  for (const mood of ['Fine', 'Busy', 'Error']) {
    const c = new Critter(el, { pose: 'icon' + mood, scale: 1, blink: false, particles: false, species: L.species, palette: L.palette });
    const px = Object.assign({}, c.buf.px);
    c.destroy();
    // drop the ground shadow (translucent)
    for (const k of Object.keys(px)) if (String(px[k]).startsWith('rgba')) delete px[k];
    out[id][mood.toLowerCase()] = px;
  }
}
// One Swift literal per provider: its palette, then rows of palette letters for each mood.
const letters = 'abcdefghijklmnopqrstuvwxyz';
let swift = '// Generated by scripts/tray-sprites.js from Resources/web/pet.js and looks.js. Don\'t edit; rerun it:\n' +
  '//   node scripts/tray-sprites.js > Sources/AiUsage/Tray/TraySprites.swift\n\n' +
  '/// Each provider\'s mini, standing still, for the menu bar icon: a palette and rows of palette letters per mood.\n' +
  'enum TraySprites {\n    struct Sprite { let palette: [String]; let fine: [String]; let busy: [String]; let error: [String] }\n\n' +
  '    static let all: [String: Sprite] = [\n';
for (const [id, moods] of Object.entries(out)) {
  const all = Object.values(moods).flatMap((m) => Object.keys(m).map((k) => k.split(',').map(Number)));
  const x0 = Math.min(...all.map((p) => p[0])), x1 = Math.max(...all.map((p) => p[0]));
  const y0 = Math.min(...all.map((p) => p[1])), y1 = Math.max(...all.map((p) => p[1]));
  const colors = [...new Set(Object.values(moods).flatMap((m) => Object.values(m)))];
  const rows = (m) => Array.from({ length: y1 - y0 + 1 }, (_, j) => Array.from({ length: x1 - x0 + 1 }, (_, i) => {
    const c = m[(x0 + i) + ',' + (y0 + j)];
    return c ? letters[colors.indexOf(c)] : '.';
  }).join(''));
  const list = (r) => '[\n' + r.map((s) => '            "' + s + '",').join('\n') + '\n        ]';
  swift += `        "${id}": Sprite(\n        palette: [${colors.map((c) => '"' + c + '"').join(', ')}],\n` +
    `        fine: ${list(rows(moods.fine))},\n        busy: ${list(rows(moods.busy))},\n        error: ${list(rows(moods.error))}),\n`;
}
swift += '    ]\n}\n';
process.stdout.write(swift);
process.exit(0);
